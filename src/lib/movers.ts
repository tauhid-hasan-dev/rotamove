const DIACRITICS = /[̀-ͯ]/g;

function slugify(name: string): string {
  return name
    .toLowerCase()
    .normalize("NFD")
    .replace(DIACRITICS, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

function corridorsFor(regions: RegionId[]): string[] {
  const set = new Set(regions);
  return CORRIDORS.filter((c) => set.has(c.from) && set.has(c.to)).map((c) => c.id);
}

